import Foundation

/// Тип, который временно хранит значения изображений в памяти.
///
/// Чтение синхронное, поэтому значение можно запрашивать прямо из
/// `cellForItemAt`. Стоимость записи задаётся в байтах и определяет,
/// какие значения кэш вытесняет.
protocol ImageMemoryCache<Value>: Sendable {
    /// Тип хранимого значения.
    ///
    /// Значение должно быть классом: ``NSCache`` хранит только ссылочные
    /// типы. Оно также должно быть ``Sendable``, потому что передаётся
    /// между потоками.
    associatedtype Value: AnyObject & Sendable

    /// Возвращает значение для заданного ключа.
    ///
    /// - Parameter key: Ключ, идентифицирующий значение.
    /// - Returns: Значение, связанное с `key`, или `nil`, если для `key`
    ///   нет значения.
    func value(for key: String) -> Value?

    /// Сохраняет значение для заданного ключа и связывает пару со стоимостью.
    ///
    /// - Parameters:
    ///   - value: Объект, который нужно поместить в кэш.
    ///   - key: Ключ, с которым связывается значение.
    ///   - cost: Стоимость пары ключ-значение в байтах. По ней кэш решает,
    ///     какие объекты вытеснять.
    func set(_ value: Value, for key: String, cost: Int)

    /// Удаляет все объекты из кэша.
    ///
    /// Вызывайте при предупреждении о нехватке памяти.
    func removeAll()
}

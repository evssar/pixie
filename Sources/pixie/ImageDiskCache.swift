import Foundation

/// Тип, который хранит байты изображений на диске.
///
/// Методы асинхронные: обращение к диску не должно блокировать
/// вызывающий поток. Ключ — ``URL`` ресурса, значение — исходные
/// байты, а не декодированное изображение.
protocol ImageDiskCache: Sendable {
    /// Возвращает байты, сохранённые для заданного адреса.
    ///
    /// Чтение асинхронное и обращается к диску, поэтому для
    /// `cellForItemAt` оно не подходит.
    ///
    /// - Parameter url: Адрес, идентифицирующий запись.
    /// - Returns: Сохранённые байты или `nil`, если записи для `url`
    ///   нет.
    func data(for url: URL) async -> Data?

    /// Сохраняет байты изображения для заданного адреса.
    ///
    /// На диск попадают переданные байты без декодирования.
    ///
    /// - Parameters:
    ///   - data: Байты, которые нужно записать на диск.
    ///   - url: Адрес, с которым связываются байты.
    func store(_ data: Data, for url: URL) async

    /// Удаляет все записи с диска.
    func removeAll() async
}
